// This file is the production build corridor. It replaces host execution with
// a Daytona sandbox end to end:
//
//	lease a base sandbox → run the pinned agent inside it → promote the
//	sandbox filesystem to a snapshot → mirror that filesystem to a host temp
//	root → verify (stage commands and assessments run back in the sandbox)
//	→ the registry boots the promoted snapshot under the isolated policy.
//
// Nothing generated by the agent runs on the host. The host only ever reads a
// copy of the tree, and the registry's promotion boot check is what proves the
// verified posture is the posture learners get.

// DefaultSandboxWorkspaceDir is the directory the agent works in inside a
// build sandbox. It matches the base snapshot's layout.
const DefaultSandboxWorkspaceDir = "/home/agent/work"

// SandboxRuntimeFactory builds an agent runtime bound to one leased sandbox.
// It is the seam where a per-build relay token is issued: the runtime reaches
// the model only through the relay, so provider keys never enter the sandbox.
type SandboxRuntimeFactory func(ctx context.Context, req environmentregistry.BuildRequest, sandbox agentruntime.SandboxExecutor) (agentruntime.AgentRuntime, func(), error)

// DaytonaBuilder implements the registry Builder by preparing environments
// inside Daytona sandboxes. Output must still pass verification and promotion
// gates; a build never establishes readiness.
type DaytonaBuilder struct {
	Client       DaytonaClient
	BaseSnapshot string
	// WorkspaceDir is the sandbox directory the agent works in.
	WorkspaceDir string
	NewRuntime   SandboxRuntimeFactory
	TurnCeiling  int
	Timeout      time.Duration
	// OutputCapBytes bounds the runtime's captured output. Zero keeps the
	// runtime default.
	OutputCapBytes int
	SnapshotTTL    time.Duration
	Labels         map[string]string
	// Materializer defaults to a SandboxTreeMaterializer that skips build
	// output directories.
	Materializer *SandboxTreeMaterializer
	// Builds receives the live build so the verifier can finish in the same
	// sandbox. Required: without it the sandbox would be closed before
	// verification, and the agent's output would never be judged.
	Builds *DaytonaBuilds
}

func (b *DaytonaBuilder) workspaceDir() string {
	if dir := strings.TrimRight(strings.TrimSpace(b.WorkspaceDir), "/"); dir != "" {
		return dir
	}
	return DefaultSandboxWorkspaceDir
}

func (b *DaytonaBuilder) materializer() SandboxTreeMaterializer {
	if b.Materializer != nil {
		return *b.Materializer
	}
	return SandboxTreeMaterializer{Skip: skipBuildOutput}
}

// skipBuildOutput keeps downloaded-then-generated directories out of the host
// mirror. Build and test still run in the sandbox against the real tree; the
// host copy only has to carry what the verifier reads.
func skipBuildOutput(rel string) bool {
	for _, part := range strings.Split(filepath.ToSlash(rel), "/") {
		switch part {
		case "target", "node_modules", ".git":
			return true
		}
	}
	return false
}

// Build prepares one environment in a fresh sandbox and returns the promoted
// snapshot reference the registry records.
func (b *DaytonaBuilder) Build(ctx context.Context, req environmentregistry.BuildRequest) (environmentregistry.BuildOutput, error) {
	if b == nil || b.Client == nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: Daytona client is required")
	}
	if b.NewRuntime == nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: sandbox runtime factory is required")
	}
	if b.Builds == nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: build registry is required")
	}
	base := strings.TrimSpace(b.BaseSnapshot)
	if base == "" {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: base snapshot is required")
	}
	reportStage(ctx, "leasing a build sandbox from the base snapshot")
	labels := map[string]string{"codegym": "environment-build"}
	for key, value := range b.Labels {
		labels[key] = value
	}
	// A build is promoted, so it must not be ephemeral: an ephemeral sandbox
	// can be reclaimed before its snapshot is used.
	sandbox, err := b.Client.Create(ctx, sandboxParams(base, labels, false, false))
	if err != nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: lease build sandbox: %w", err)
	}
	workspaceDir := b.workspaceDir()
	build := &daytonaBuild{sandbox: sandbox, workspaceDir: workspaceDir}
	// From here on every failure must release the sandbox; a leaked build
	// sandbox is a leaked machine.
	keep := false
	defer func() {
		if !keep {
			build.release(context.WithoutCancel(ctx))
		}
	}()

	runtime, releaseRuntime, err := b.NewRuntime(ctx, req, sandbox)
	if err != nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: start sandbox agent runtime: %w", err)
	}
	if releaseRuntime != nil {
		defer releaseRuntime()
	}

	reportStage(ctx, "agent building the project and resolving dependencies")
	started := time.Now()
	runResult, err := runtime.Run(ctx, agentruntime.TaskSpec{
		Goal:             envbuild.PreparationInstructions(req.Technology, req.Objective),
		WorkingDirectory: workspaceDir,
		AllowedTools: []agentruntime.Tool{
			agentruntime.ToolReadFile,
			agentruntime.ToolWriteFile,
			agentruntime.ToolShell,
			agentruntime.ToolReportProgress,
		},
		TurnCeiling:    b.turnCeiling(),
		Deadline:       time.Now().Add(b.timeout()),
		OutputCapBytes: b.OutputCapBytes,
	})
	telemetry := builderTelemetry(runResult.Telemetry, time.Since(started))
	if err != nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: sandbox preparation failed: %w", err)
	}
	if runResult.Telemetry.Termination != agentruntime.TerminationCompleted {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: sandbox preparation ended: %s%s",
			runResult.Telemetry.Termination, failureSuffix(runResult.OutputTail))
	}

	reportStage(ctx, "promoting the built filesystem to a snapshot")
	snapshotName, err := b.promote(ctx, sandbox, req)
	if err != nil {
		return environmentregistry.BuildOutput{}, err
	}
	build.snapshot = snapshotName

	reportStage(ctx, "reading the built tree back for verification")
	localRoot, err := os.MkdirTemp("", "codegym-build-")
	if err != nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: create build mirror: %w", err)
	}
	build.localRoot = localRoot
	materializer := b.materializer()
	// The materializer reads from the sandbox that produced this build.
	materializer.Executor = sandbox
	if err := materializer.Materialize(ctx, workspaceDir, localRoot); err != nil {
		return environmentregistry.BuildOutput{}, err
	}

	manifest, diagnostics, err := envbuild.DraftManifest(envbuild.BuildRequest{
		Technology: req.Technology,
		Objective:  req.Objective,
	}, localRoot)
	if err != nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: draft manifest from sandbox build: %w", err)
	}
	for _, diagnostic := range diagnostics {
		if diagnostic.Severity == "error" {
			return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: sandbox preparation produced no manifest: %s", diagnostic.Message)
		}
	}
	if manifest == nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: sandbox preparation produced no manifest")
	}
	manifestPath, err := WriteManifest(localRoot, manifest)
	if err != nil {
		return environmentregistry.BuildOutput{}, err
	}
	raw, err := os.ReadFile(filepath.Join(localRoot, manifestPath))
	if err != nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: read back proposed manifest: %w", err)
	}
	parsed, err := environmentverify.ParseManifest(raw)
	if err != nil {
		return environmentregistry.BuildOutput{}, fmt.Errorf("envintegration: builder output rejected by manifest parser: %w", err)
	}

	build.manifestPath = manifestPath
	b.Builds.register(build)
	keep = true
	return environmentregistry.BuildOutput{
		Builder: ToBuilderResult(
			newBuilderRunID(), b.runtimeName(),
			agentruntime.OpenCodePinnedVersion,
			&environmentverify.SandboxRef{Provider: DaytonaSandboxProvider, ID: snapshotName},
			manifestPath, diagnostics, telemetry,
		),
		SnapshotRef: snapshotName,
		Manifest:    parsed,
	}, nil
}

// promote creates the reusable snapshot that backs the artifact. The name is
// derived from the request so operators can recognize a snapshot later.
func (b *DaytonaBuilder) promote(ctx context.Context, sandbox SnapshottingSandbox, req environmentregistry.BuildRequest) (string, error) {
	raw := make([]byte, 6)
	if _, err := rand.Read(raw); err != nil {
		return "", err
	}
	name := snapshotName(req.Technology, req.Version, hex.EncodeToString(raw))
	return PromoteSnapshot(ctx, sandbox, name, b.snapshotTTL())
}

func (b *DaytonaBuilder) runtimeName() string { return "opencode-sandbox" }

func (b *DaytonaBuilder) turnCeiling() int {
	if b.TurnCeiling > 0 {
		return b.TurnCeiling
	}
	return 32
}

func (b *DaytonaBuilder) timeout() time.Duration {
	if b.Timeout > 0 {
		return b.Timeout
	}
	return 20 * time.Minute
}

func (b *DaytonaBuilder) snapshotTTL() time.Duration {
	if b.SnapshotTTL > 0 {
		return b.SnapshotTTL
	}
	return 15 * time.Minute
}

// DaytonaSandboxProvider names the snapshot provider in builder sandbox refs.
const DaytonaSandboxProvider = "daytona"

// snapshotName builds a Daytona snapshot name: lowercase alphanumerics and
// dashes, so it is always a legal snapshot identifier whatever the request
// contained.
func snapshotName(technology, version, suffix string) string {
	parts := []string{"codegym"}
	parts = append(parts, sanitizeSnapshotPart(technology))
	if v := sanitizeSnapshotPart(version); v != "" {
		parts = append(parts, v)
	}
	parts = append(parts, suffix)
	return strings.Join(parts, "-")
}

func sanitizeSnapshotPart(value string) string {
	value = strings.ToLower(strings.TrimSpace(value))
	cleaned := strings.Map(func(r rune) rune {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			return r
		case r == '.', r == '_', r == ' ', r == '/':
			return '-'
		default:
			return -1
		}
	}, value)
	cleaned = strings.Trim(cleaned, "-")
	for strings.Contains(cleaned, "--") {
		cleaned = strings.ReplaceAll(cleaned, "--", "-")
	}
	return cleaned
}

// newBuilderRunID identifies one build attempt.
func newBuilderRunID() string {
	raw := make([]byte, 8)
	if _, err := rand.Read(raw); err != nil {
		return fmt.Sprintf("build_%d", time.Now().UnixNano())
	}
	return "build_" + hex.EncodeToString(raw)
}

// builderTelemetry maps runtime telemetry onto the shared builder contract.
// failureSuffix attaches the runtime's bounded output tail to an error.
func failureSuffix(tail string) string {
	if strings.TrimSpace(tail) == "" {
		return ""
	}
	return ": " + tail
}

func builderTelemetry(telemetry agentruntime.Telemetry, wallTime time.Duration) envbuild.BuilderTelemetry {
	return envbuild.BuilderTelemetry{
		WallTimeMs:       wallTime.Milliseconds(),
		TokensIn:         telemetry.Tokens.Input,
		TokensOut:        telemetry.Tokens.Output,
		EstimatedCostUsd: float64(telemetry.CostUSDMicros) / 1_000_000,
		RepairIterations: telemetry.RepairIterations,
	}
}

// daytonaBuild is one build between Build and Verify: the leased sandbox, the
// mirror of its tree, and the snapshot under promotion.
type daytonaBuild struct {
	sandbox      SnapshottingSandbox
	workspaceDir string
	localRoot    string
	manifestPath string
	snapshot     string
	closed       bool
}

// release closes the sandbox and removes the host mirror. It is idempotent
// and never deletes the promoted snapshot: only a rejected verdict does that.
func (b *daytonaBuild) release(ctx context.Context) {
	if b == nil || b.closed {
		return
	}
	b.closed = true
	if b.sandbox != nil {
		if err := b.sandbox.Delete(ctx); err != nil {
			reportStage(ctx, "warning: build sandbox did not release")
		}
	}
	if b.localRoot != "" {
		_ = os.RemoveAll(b.localRoot)
	}
}

// DaytonaBuilds tracks live builds between Build and Verify. A single build is
// split across the two registry interfaces, so the sandbox and its mirror have
// to survive the handoff; this is that handoff, exactly as SnapshotDirectories
// is for the host corridor.
type DaytonaBuilds struct {
	mu      sync.Mutex
	entries map[string]*daytonaBuild
}

func (r *DaytonaBuilds) register(build *daytonaBuild) {
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.entries == nil {
		r.entries = map[string]*daytonaBuild{}
	}
	r.entries[build.snapshot] = build
}

func (r *DaytonaBuilds) take(reference string) (*daytonaBuild, bool) {
	r.mu.Lock()
	defer r.mu.Unlock()
	build, ok := r.entries[reference]
	if !ok {
		return nil, false
	}
	delete(r.entries, reference)
	return build, true
}

// DaytonaVerifier completes verification inside the same sandbox the agent
// built in. Its roots resolve to the host mirror downloaded at build time, so
// the verifier's file reads see the built bytes, while every stage command and
// assessment runs back in the sandbox.
type DaytonaVerifier struct {
	Client DaytonaClient
	Builds *DaytonaBuilds
	// Assessments resolves the demo-mode correct/wrong solutions from the
	// built artifact. The sandbox assessor replaces its host assessor.
	Assessments *StarterAssessmentSource
	Timeouts    environmentverify.StageTimeouts
	// ScratchDir is the sandbox directory assessments upload into.
	ScratchDir string
	Labels     map[string]string
}

// Verify judges one sandbox build: it runs the verification stages and
// assessments in the build sandbox, then releases the sandbox. A rejected
// verdict also deletes the snapshot, so only verified artifacts can boot later.
func (v *DaytonaVerifier) Verify(ctx context.Context, build environmentregistry.BuildOutput) environmentverify.VerifierResult {
	if v == nil || v.Builds == nil {
		return platformRejection(build, "envintegration: build registry is required")
	}
	entry, ok := v.Builds.take(build.SnapshotRef)
	if !ok {
		return platformRejection(build, fmt.Sprintf("envintegration: no live build for snapshot %q", build.SnapshotRef))
	}
	reportStage(ctx, "verifying build, tests, and starter in the sandbox")
	// The sandbox is released after verification either way; the snapshot is
	// only removed when the verdict is not verified.
	defer func() {
		entry.release(context.WithoutCancel(ctx))
	}()

	root := entry.localRoot
	resolveRoot := func(string) (string, error) { return root, nil }
	inner := &RegistryVerifier{
		Roots: resolveRoot,
		Runner: &SandboxCommandRunner{
			Executor: entry.sandbox,
			Paths:    SandboxPathMapper{LocalRoot: root, RemoteRoot: entry.workspaceDir},
		},
		// Setup is satisfied because the verified filesystem is the one the
		// agent already set up and that this build promotes.
		SetupAlreadySatisfied: true,
		Timeouts:              v.Timeouts,
	}
	source := v.Assessments
	if source == nil {
		source = &StarterAssessmentSource{}
	}
	configured := *source
	configured.Roots = resolveRoot
	configured.Assessor = &SandboxAssessor{
		Executor:   entry.sandbox,
		ScratchDir: v.ScratchDir,
	}
	result := (&AssessmentResolvingVerifier{Inner: inner, Assessments: &configured}).Verify(ctx, build)
	if result.Verdict != environmentverify.VerdictVerified {
		// An unverified artifact must not leave a bootable snapshot behind.
		if err := v.Client.DeleteSnapshot(context.WithoutCancel(ctx), build.SnapshotRef); err != nil && v.Client != nil {
			reportStage(ctx, "warning: rejected snapshot did not delete")
		}
	}
	return result
}

// platformRejection builds a platform-fault verdict for a verifier that cannot
// even start, matching RegistryVerifier's pre-check rejections.
func platformRejection(build environmentregistry.BuildOutput, message string) environmentverify.VerifierResult {
	stage := environmentverify.StagePlatform
	return environmentverify.VerifierResult{
		SchemaVersion: environmentverify.VerifierResultSchemaVersion,
		VerifierRunID: newVerifierRunID(),
		BuilderRunID:  build.Builder.BuilderRunID,
		Verdict:       environmentverify.VerdictRejected,
		FailedStage:   &stage,
		Repairable:    false,
		Diagnostics: []environmentverify.Diagnostic{{
			Severity: "error",
			Stage:    stage,
			Code:     environmentverify.CodePlatformFault,
			Message:  message,
		}},
		Promotion: environmentverify.Promotion{Allowed: false, Reason: message},
	}
}
