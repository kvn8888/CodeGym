import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const registryPath = path.join(repoRoot, 'api', 'memory-events.registry.json');
const frontendOutPath = path.join(repoRoot, 'frontend', 'src', 'shared', 'api', 'memoryEvents.ts');
const backendOutPath = path.join(repoRoot, 'backend', 'internal', 'memory', 'event_names.go');

const checkMode = process.argv.includes('--check');

function readRegistry() {
  const raw = fs.readFileSync(registryPath, 'utf8');
  return JSON.parse(raw);
}

function renderFrontend(registry) {
  const sources = registry.sources;
  const types = registry.types;

  const sourceLines = sources
    .map((source) => `  ${source.key}: '${source.value}',`)
    .join('\n');

  const typeLines = [];
  for (const type of types) {
    typeLines.push(`  ${type.key}: '${type.value}',`);
  }

  const aliasTypes = types.filter((type) => Array.isArray(type.aliases) && type.aliases.length > 0);
  if (aliasTypes.length > 0) {
    typeLines.push('');
    typeLines.push('  // Compatibility aliases while callers migrate to guide-aligned names.');
    for (const type of aliasTypes) {
      for (const alias of type.aliases) {
        typeLines.push(`  ${alias.key}: '${alias.value}',`);
      }
    }
  }

  const builderLines = sources
    .map(
      (source) => `export function ${source.builder}(input: BuildMemoryEventInput) {\n  return buildMemoryEvent(memoryEventSources.${source.key}, input);\n}`,
    )
    .join('\n\n');

  return `// Code generated by scripts/generate-memory-event-registry.mjs. DO NOT EDIT.\nimport type { components } from './openapi';\n\nexport const memoryEventSources = {\n${sourceLines}\n} as const;\n\nexport type MemoryEventSource = (typeof memoryEventSources)[keyof typeof memoryEventSources];\n\nexport const memoryEventTypes = {\n${typeLines.join('\n')}\n} as const;\n\nexport type MemoryEventType = (typeof memoryEventTypes)[keyof typeof memoryEventTypes];\nexport type MemoryEventInput = components['schemas']['RecordMemoryEventInput'];\nexport type MemoryEventPayload = components['schemas']['JsonValue'];\n\ninterface BuildMemoryEventInput {\n  type: MemoryEventType;\n  summary: string;\n  payload?: MemoryEventPayload;\n  occurredAt?: string | Date;\n}\n\nfunction toOccurredAt(value?: string | Date) {\n  if (!value) {\n    return undefined;\n  }\n\n  return (value instanceof Date ? value : new Date(value)).toISOString();\n}\n\nfunction buildMemoryEvent(source: MemoryEventSource, input: BuildMemoryEventInput): MemoryEventInput {\n  return {\n    source,\n    type: input.type,\n    summary: input.summary,\n    ...(input.payload === undefined ? {} : { payload: input.payload }),\n    ...(toOccurredAt(input.occurredAt) ? { occurred_at: toOccurredAt(input.occurredAt) } : {}),\n  };\n}\n\n${builderLines}\n`;
}

function renderBackend(registry) {
  const sources = registry.sources;
  const types = registry.types;

  const sourceConstLines = sources
    .map((source) => `\t${source.goConst} = \"${source.value}\"`)
    .join('\n');

  const typeConstLines = types
    .map((type) => `\t${type.goConst} = \"${type.value}\"`)
    .join('\n');

  const typesBySource = new Map();
  for (const source of sources) {
    typesBySource.set(source.value, []);
  }
  for (const type of types) {
    typesBySource.get(type.source).push(type.goConst);
  }

  const mapBody = sources
    .map((source) => {
      const sourceTypes = typesBySource.get(source.value) ?? [];
      const lines = sourceTypes.map((goConst) => `\t\t${goConst}: {},`).join('\n');
      return `\t${source.goConst}: {\n${lines}\n\t},`;
    })
    .join('\n');

  return `// Code generated by scripts/generate-memory-event-registry.mjs. DO NOT EDIT.\npackage memory\n\nimport \"fmt\"\n\n// Event source names shared across frontend/backend emitters.\nconst (\n${sourceConstLines}\n)\n\n// Event type names approved in docs/memory-event-naming-guide-v0.md.\nconst (\n${typeConstLines}\n)\n\nvar allowedEventTypesBySource = map[string]map[string]struct{}{\n${mapBody}\n}\n\n// ValidateEventName enforces the approved source/type registry for new writes.\nfunc ValidateEventName(source, eventType string) error {\n\ttypesForSource, ok := allowedEventTypesBySource[source]\n\tif !ok {\n\t\treturn fmt.Errorf(\"unknown memory event source %q\", source)\n\t}\n\tif _, ok := typesForSource[eventType]; !ok {\n\t\treturn fmt.Errorf(\"unknown memory event type %q for source %q\", eventType, source)\n\t}\n\treturn nil\n}\n`;
}

function writeOrCheck(filePath, nextContent) {
  if (!fs.existsSync(filePath)) {
    if (checkMode) {
      throw new Error(`Missing generated file: ${path.relative(repoRoot, filePath)}`);
    }
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, nextContent);
    return;
  }

  const current = fs.readFileSync(filePath, 'utf8');
  if (current === nextContent) {
    return;
  }

  if (checkMode) {
    throw new Error(`Generated file is out of date: ${path.relative(repoRoot, filePath)}`);
  }

  fs.writeFileSync(filePath, nextContent);
}

function main() {
  const registry = readRegistry();
  const frontend = renderFrontend(registry);
  const backend = renderBackend(registry);

  writeOrCheck(frontendOutPath, frontend);
  writeOrCheck(backendOutPath, backend);

  if (!checkMode) {
    console.log('Generated memory event files from registry.');
  } else {
    console.log('Memory event generated files are up to date.');
  }
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
